
kilometros = float(input("Ingresa una distancia en kilómetros: "))
metros = kilometros * 1000
centimetros = kilometros * 100000
millas = kilometros * 0.621371
print("\n--- Conversión de unidades ---")
print(f"Distancia en kilómetros: {kilometros:.2f} km")
print(f"Distancia en metros:     {metros:.2f} m")
print(f"Distancia en centímetros: {centimetros:.2f} cm")
print(f"Distancia en millas:     {millas:.2f} millas")